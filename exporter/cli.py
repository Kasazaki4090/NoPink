"""CLI entry point for FeedSieve blacklist exporter."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from exporter.generator import export_for_feedsieve


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Export NoPink keywords.json into FeedSieve-compatible wordlists."
    )
    parser.add_argument(
        "--input",
        default=Path("output/keywords.json"),
        type=Path,
        help="Input keywords.json generated by analyzer.",
    )
    parser.add_argument(
        "--out-dir",
        default=Path("output/feedsieve"),
        type=Path,
        help="Output directory for FeedSieve files.",
    )
    parser.add_argument(
        "--max-risk",
        choices=["low", "medium", "high"],
        default="low",
        help="Maximum false-positive risk level to include.",
    )
    parser.add_argument(
        "--pack-id",
        default="nopink-custom",
        help="Keyword pack ID in YAML output.",
    )
    args = parser.parse_args()

    data = json.loads(args.input.read_text(encoding="utf-8"))
    outputs = export_for_feedsieve(
        data,
        out_dir=args.out_dir,
        max_risk=args.max_risk,
        pack_id=args.pack_id,
    )
    print("[NoPink] FeedSieve 词库已生成:")
    for kind, path in outputs.items():
        print(f"  - {kind}: {path}")


if __name__ == "__main__":
    main()
