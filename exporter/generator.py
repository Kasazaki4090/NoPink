"""Generate FeedSieve muted words (.txt), keyword-pack (.yaml), and report (.json)."""

from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

import yaml

RISK_ORDER = {"low": 0, "medium": 1, "high": 2}


def filter_keywords(
    keywords_data: dict[str, Any],
    max_risk: str = "low",
) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    """Filter core_keywords by max allowed false_positive_risk."""
    threshold = RISK_ORDER.get(max_risk.lower(), 0)
    kept: list[dict[str, Any]] = []
    dropped: list[dict[str, Any]] = []
    seen: set[str] = set()

    for item in keywords_data.get("core_keywords", []):
        term = str(item.get("term", "")).strip()
        if not term or term in seen:
            continue
        seen.add(term)
        risk = str(item.get("false_positive_risk", "medium")).lower()
        if RISK_ORDER.get(risk, 1) <= threshold:
            kept.append(item)
        else:
            dropped.append(item)

    return kept, dropped


def export_for_feedsieve(
    keywords_data: dict[str, Any],
    out_dir: Path,
    max_risk: str = "low",
    pack_id: str = "nopink-custom",
) -> dict[str, Path]:
    """Write FeedSieve .txt muted words, .yaml keyword-pack, and .json report."""
    out_dir.mkdir(parents=True, exist_ok=True)
    kept, dropped = filter_keywords(keywords_data, max_risk=max_risk)
    terms = [str(item["term"]).strip() for item in kept]

    txt_path = out_dir / "feedsieve_muted_words.txt"
    txt_content = "\n".join(terms) + ("\n" if terms else "")
    txt_path.write_text(txt_content, encoding="utf-8", newline="\n")

    yaml_path = out_dir / "feedsieve_keyword_pack.yaml"
    pack_obj = {
        "id": pack_id,
        "name": "NoPink Custom Blacklist",
        "description": "Generated by NoPink local AI pipeline for FeedSieve.",
        "version": "1.0.0",
        "updatedAt": datetime.now(timezone.utc).isoformat(),
        "maxRisk": max_risk,
        "keywords": [
            {
                "term": str(item["term"]).strip(),
                "score": item.get("score", 0),
                "risk": item.get("false_positive_risk", "low"),
                "reason": item.get("reason", ""),
            }
            for item in kept
        ],
    }
    yaml_path.write_text(
        yaml.safe_dump(pack_obj, allow_unicode=True, sort_keys=False),
        encoding="utf-8",
        newline="\n",
    )

    report_path = out_dir / "feedsieve_report.json"
    report_obj = {
        "generatedAt": datetime.now(timezone.utc).isoformat(),
        "maxRisk": max_risk,
        "keptCount": len(kept),
        "droppedByRiskCount": len(dropped),
        "excludedCommonCount": len(keywords_data.get("excluded_common_words", [])),
        "keptTerms": terms,
        "droppedByRisk": dropped,
        "excludedCommonWords": keywords_data.get("excluded_common_words", []),
    }
    report_path.write_text(
        json.dumps(report_obj, ensure_ascii=False, indent=2),
        encoding="utf-8",
        newline="\n",
    )

    return {
        "txt": txt_path,
        "yaml": yaml_path,
        "report": report_path,
    }
